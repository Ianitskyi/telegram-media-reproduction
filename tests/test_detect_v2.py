def test_no_false_positives():
    bad = {t: names(t) for t in FALSE_POSITIVES if names(t)}
    assert not bad, bad


def test_true_positives():
    missed = [(t, n, names(t)) for t, n in TRUE_POSITIVES if n not in names(t)]
    assert not missed, missed


def test_links_from_urls_only():
    assert D.link_ids(["https://www.pravda.com.ua/news/1)"]) == {3}
    assert D.link_ids(["https://kmu.gov.ua/"]) == set()
    assert D.link_ids(["https://ua.krymr.com/a/1"]) == {41}


def test_self_reference():
    r = D.analyze({"text": "Подробиці на сайті Суспільне", "urls": ["https://suspilne.media/1"]}, "suspilnenews")
    assert r["self_link"] and r["self_mention"] and not r["link_ids"] and not r["mention_ids"]
